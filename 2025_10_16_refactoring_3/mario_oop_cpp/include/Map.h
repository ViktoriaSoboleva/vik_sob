#pragma once

#include "constants.h"

// ============================================================
//  class Map — символьный буфер экрана
//  Хранит двумерный массив символов и умеет его рисовать.
//  Ничего не знает об игровой логике — только отрисовка.
// ============================================================
class Map {
    // Двумерный массив символов: MAP_H строк по (MAP_W + 1) символов
    // +1 для нуль-терминатора '\0' в конце каждой строки
    char grid[MAP_H][MAP_W + 1];

public:
    // Заполняет весь буфер пробелами (очищает экран перед новым кадром)
    void clear();

    // Ставит символ ch в позицию (x, y) буфера
    // Если координаты выходят за пределы — ничего не делает
    void setChar(int x, int y, char ch);

    // Печатает строку "Score: N" в строке 1 буфера, начиная с позиции 5
    void putScore(int score);

    // Выводит весь буфер на экран
    void render();
};
